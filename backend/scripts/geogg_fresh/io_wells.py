# 3. Deviation surveys
# =============================================================================
@dataclass
class DeviationSurvey:
    well: str
    stations: pd.DataFrame          # columns: md_m, azim_deg, incl_deg, null_filled (bool)
    meta: dict = field(default_factory=dict)


def parse_deviation(path: str | Path, well: str, null_values=(-999.25, -999.0, -9999.0),
                    default_order=("md", "incl", "azim")) -> DeviationSurvey:
    """Parse a deviation survey; detect column order from the '#' header lines.

    Null azimuth/inclination rows (e.g. o-2 at TD) are *kept* and filled by holding
    the previous valid direction - flagged in ``null_filled`` and in ``meta``.
    """
    path = Path(path)
    header, rows = [], []
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            header.append(line.lstrip("#").strip())
            continue
        parts = re.split(r"[\s,;]+", line)
        try:
            rows.append([float(v) for v in parts[:3]])
        except ValueError:
            header.append(line)   # a text line in the data block - keep it as metadata
    if not rows:
        raise WellDataError(f"No numeric rows in deviation file {path}")

    order, md_unit = [], "m"
    for name in header:
        up = name.upper().strip()
        if up == well.upper() or up == "DEVIATION":
            continue                      # title lines, not column names
        if up.startswith("MD") or up.startswith("DEPTH") or "MEASURED" in up:
            order.append("md")
            if "(FT" in up or "FEET" in up:
                md_unit = "ft"
        elif "AZI" in up:
            order.append("azim")
        elif "INC" in up:
            order.append("incl")
    meta = {"path": str(path), "header_lines": header, "md_unit_in_file": md_unit,
            "column_order_source": "file_header", "flags": []}
    if sorted(order) != ["azim", "incl", "md"]:
        order = list(default_order)
        meta["column_order_source"] = "ASSUMED_DEFAULT (header did not name all 3 columns)"
        meta["flags"].append("column_order_assumed")
    meta["column_order"] = order

    arr = np.asarray(rows, dtype=float)
    data = {name: arr[:, i] for i, name in enumerate(order)}
    md = data["md"] * (FT_TO_M if md_unit == "ft" else 1.0)
    azim = data["azim"].copy()
    incl = data["incl"].copy()
    nulls = np.zeros(len(md), dtype=bool)
    for nv in null_values:
        nulls |= np.isclose(azim, nv) | np.isclose(incl, nv)
    azim[nulls] = np.nan
    incl[nulls] = np.nan
    if nulls.any():
        meta["flags"].append(f"null_direction_rows={int(nulls.sum())} at MD {md[nulls].round(2).tolist()} "
                             f"(direction held from previous station)")
    # hold previous valid direction for null rows (documented, flagged)
    incl_f = pd.Series(incl).ffill().fillna(0.0).to_numpy()
    azim_f = pd.Series(azim).ffill().fillna(0.0).to_numpy()

    if np.any(np.diff(md) <= 0):
        meta["flags"].append("md_not_strictly_increasing")
    bad_inc = (incl_f < 0) | (incl_f > 180)
    if bad_inc.any():
        meta["flags"].append(f"inclination_out_of_range_rows={int(bad_inc.sum())}")
    if np.nanmax(incl_f) > 90:
        meta["flags"].append("inclination_above_90deg (horizontal/upward section - check column order)")
    bad_az = (azim_f < 0) | (azim_f > 360)
    if bad_az.any():
        meta["flags"].append(f"azimuth_out_of_range_rows={int(bad_az.sum())}")
    azim_f = np.mod(azim_f, 360.0)
    gaps = np.diff(md)
    meta.update({
        "n_stations": int(len(md)), "md_min_m": float(md.min()), "md_max_m": float(md.max()),
        "max_station_gap_m": float(gaps.max()) if len(gaps) else 0.0,
        "max_incl_deg": float(np.nanmax(incl_f)),
        "all_zero_inclination": bool(np.allclose(incl_f, 0.0)),
        "n_null_rows": int(nulls.sum()),
    })
    if meta["all_zero_inclination"]:
        meta["flags"].append("all_inclinations_zero (vertical well OR placeholder survey - unverified)")
    if md[0] > 0:
        meta["flags"].append(f"survey_starts_below_datum_at_{md[0]:.1f}m (vertical tie-on assumed)")
    stations = pd.DataFrame({"md_m": md, "azim_deg": azim_f, "incl_deg": incl_f, "null_filled": nulls})
    return DeviationSurvey(well=well, stations=stations, meta=meta)


