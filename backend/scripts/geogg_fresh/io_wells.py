# 2. Finding files for each well (patterns, not hard-coded names)
# =============================================================================
class FileIndex:
    """Index every file below some folders once, then match per-well patterns.

    Patterns use ``{well}`` as placeholder and shell wildcards, e.g.
    ``"{well}_Deviation.txt"``.  Matching is case-insensitive.  When several files
    match, files closest to the top folder win (so ``deviations/no-1_Deviation.txt``
    beats ``deviations/Dev2 for Pet/no-1_Deviation.txt``) and the alternatives are
    reported, never silently dropped.
    """

    def __init__(self, roots: list[Path]):
        self.roots = [Path(r) for r in roots if r is not None]
        self.files: list[tuple[Path, Path]] = []      # (root, file)
        for root in self.roots:
            if root.is_dir():
                for p in sorted(root.rglob("*")):
                    if p.is_file():
                        self.files.append((root, p))

    def find(self, well: str, patterns: list[str]) -> list[Path]:
        hits = []
        for pi, pattern in enumerate(patterns):
            regex = re.compile(fnmatch.translate(pattern.format(well=well)), re.IGNORECASE)
            for root, p in self.files:
                if regex.match(p.name):
                    depth = len(p.relative_to(root).parts)
                    hits.append((depth, pi, str(p).lower(), p))
        hits.sort()
        seen, ordered = set(), []
        for *_, p in hits:
            if p not in seen:
                seen.add(p)
                ordered.append(p)
        return ordered


