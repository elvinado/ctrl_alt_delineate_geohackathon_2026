@dataclass
class LasData:
    well: str
    path: str
    reader: str
    curves: list[dict]            # mnemonic, unit, descr
    data: pd.DataFrame            # all curves (first column = depth index, file units)
    depth_mnemonic: str
    depth_unit: str               # 'm' | 'ft' | unit string
    depth_m: np.ndarray
    well_items: dict
    null_value: float | None
    warnings: list = field(default_factory=list)


def read_las(path: str | Path, well: str) -> LasData:
    """Read a LAS file with lasio if available, else with the built-in reader."""
    try:
        import lasio  # type: ignore
    except Exception:
        lasio = None
    if lasio is not None and callable(getattr(lasio, "read", None)):
        las = lasio.read(str(path), ignore_header_errors=True)
        curves = [{"mnemonic": c.mnemonic, "unit": c.unit or "", "descr": c.descr or ""} for c in las.curves]
        data = pd.DataFrame({c.mnemonic: np.asarray(c.data, dtype=float) for c in las.curves})
        items = {i.mnemonic: {"unit": i.unit, "value": i.value, "descr": i.descr} for i in las.well}
        null = items.get("NULL", {}).get("value")
        reader = f"lasio {getattr(lasio, '__version__', '?')}"
    else:
        curves, data, items, null = _read_las_builtin(Path(path))
        reader = "builtin_las2_reader (lasio unavailable)"
    if data.shape[1] == 0:
        raise WellDataError(f"LAS file has no curves: {path}")
    depth_mn = curves[0]["mnemonic"]
    unit = (curves[0]["unit"] or items.get("STRT", {}).get("unit") or "").strip().upper()
    if unit in ("M", "METER", "METERS", "METRE", "METRES"):
        depth_unit, factor = "m", 1.0
    elif unit in ("F", "FT", "FEET", "FOOT"):
        depth_unit, factor = "ft", FT_TO_M
    else:
        depth_unit, factor = unit or "unknown", 1.0
    warnings = []
    if depth_unit not in ("m", "ft"):
        warnings.append(f"depth unit '{unit}' not recognised - treated as metres (UNVERIFIED)")
    try:
        null_value = float(null) if null is not None else None
    except (TypeError, ValueError):
        null_value = None
    return LasData(well=well, path=str(path), reader=reader, curves=curves, data=data,
                   depth_mnemonic=depth_mn, depth_unit=depth_unit,
                   depth_m=data.iloc[:, 0].to_numpy(dtype=float) * factor, well_items=items,
                   null_value=null_value, warnings=warnings)


_LAS_ITEM = re.compile(r"^(?P<mnem>[^.]*)\.(?P<unit>\S*)\s*(?P<rest>.*)$")


def _read_las_builtin(path: Path):
    """Minimal LAS 2.0 reader (unwrapped files).  Wrapped files need lasio."""
    sections: dict[str, list[str]] = {}
    data_tokens: list[str] = []
    current = None
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("~"):
                current = line[1:2].upper()
                sections.setdefault(current, [])
                continue
            if current == "A":
                data_tokens.extend(line.split())
            elif current:
                sections[current].append(line)

    def items(sec):
        out = {}
        for line in sections.get(sec, []):
            m = _LAS_ITEM.match(line)
            if not m:
                continue
            rest = m.group("rest")
            value, _, descr = rest.rpartition(":") if ":" in rest else (rest, "", "")
            key = m.group("mnem").strip()
            base, n = key, 1
            while key in out:                  # duplicate mnemonics -> GR, GR:1, ...
                key, n = f"{base}:{n}", n + 1
            out[key] = {"unit": m.group("unit").strip(), "value": value.strip(), "descr": descr.strip()}
        return out

    version = items("V")
    if str(version.get("WRAP", {}).get("value", "NO")).upper().startswith("Y"):
        raise WellDataError(f"{path.name} is a wrapped LAS file - install lasio (pip install lasio)")
    well_items = items("W")
    curve_items = items("C")
    curves = [{"mnemonic": k, "unit": v["unit"], "descr": v["descr"]} for k, v in curve_items.items()]
    ncol = len(curves)
    values = np.array(data_tokens, dtype=float)
    if ncol == 0 or values.size % ncol != 0:
        raise WellDataError(f"{path.name}: {values.size} data values do not fit {ncol} curves")
    values = values.reshape(-1, ncol)
    null = well_items.get("NULL", {}).get("value", "-999.25")
    try:
        null_f = float(null)
        values[np.isclose(values, null_f)] = np.nan
    except ValueError:
        pass
    data = pd.DataFrame(values, columns=[c["mnemonic"] for c in curves])
    return curves, data, well_items, null


