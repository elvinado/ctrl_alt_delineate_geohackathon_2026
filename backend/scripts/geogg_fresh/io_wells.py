"""Readers for well data: header workbook, LAS logs, deviation surveys, T-Z tables.

Design rules (from AGENTS.md)
-----------------------------
* **Read headers, not just filenames.**  Every reader returns the parsed data
  *and* a ``meta`` dict describing what was found (units, column order, nulls,
  provenance lines) so stage 00 can inventory it honestly.
* **Never repair silently.**  Odd things (null survey rows, missing units,
  percent-scaled fractions) are *flagged*, original values are kept.
* **No new dependency is mandatory.**  ``lasio`` is used when installed; a small
  built-in LAS 2.0 reader is the fallback (your env currently has no lasio).

Formats verified against the real Challenge 1/2 files (Drive copy, 2026-11-03)
-------------------------------------------------------------------------------
* Deviation ``<well>_Deviation.txt``: ``#`` header lines ``#<well>``,
  ``#Deviation``, ``#MDKB (m)``, ``#AZIM``, ``#INCL`` -> **column order is
  MD, AZIMUTH, INCLINATION** (not the more common MD, INC, AZI).  o-2 ends with a
  ``-999.25`` null row at TD.
* Time-depth ``<well>_CS.txt`` (Petrel checkshot export): line 1 description
  (``"m-1" checkshots generated by apgce_team_10 on ...``), line 2 = number of
  columns, then column names (MDKB, TWT, TVDSS), then fixed-width data.
* Well header workbook: columns No., Well Name, RT, WD, WB, TD, Well Types, X, Y,
  Deviations, Checkshots, Markers, Las ('/' = available, 'X' = not available).
"""

from __future__ import annotations

import fnmatch
import re
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

FT_TO_M = 0.3048


class WellDataError(RuntimeError):
    """A well file exists but cannot be interpreted safely."""


# =============================================================================
# 1. Well header workbook
# =============================================================================
_HEADER_COLUMN_MAP = {
    "well name": "well", "well": "well", "wellname": "well",
    "rt": "rt_m", "kb": "rt_m", "kb elevation": "rt_m", "datum elevation": "rt_m",
    "wd": "water_depth_m", "water depth": "water_depth_m",
    "wb": "wb", "td": "td_m", "total depth": "td_m",
    "well types": "well_type", "well type": "well_type",
    "x": "x", "y": "y",
    "deviations": "flag_deviation", "checkshots": "flag_checkshot",
    "markers": "flag_markers", "las": "flag_las", "no.": "row_no",
}


def _flag_value(value) -> str:
    text = str(value).strip()
    if text in ("/", "✓", "Y", "y", "yes", "Yes"):
        return "available"
    if text in ("X", "x", "N", "n", "no", "No"):
        return "not_available"
    return "unknown" if text in ("", "nan", "None") else f"raw:{text}"


def _norm_header(value) -> str:
    """'Well_Name ' / 'WELL  NAME' -> 'well name' (case, spaces and underscores do not matter)."""
    return " ".join(str(value).replace("_", " ").strip().lower().split())


_WELL_KEYS = {"well name", "well", "wellname"}


def read_well_header(path: str | Path, max_header_row: int = 30) -> tuple[pd.DataFrame, dict]:
    """Read the organiser's well list (xlsx or csv) into standard column names.

    The header row may sit below title / note rows: the first row (of the first sheet that has one) within
    ``max_header_row`` rows that contains a 'Well Name' cell is used; ``meta['header_row']`` records it.
    """
    path = Path(path)
    meta: dict = {"path": str(path), "reader": None, "sheet": None, "header_row": 0, "unmapped_columns": []}
    if path.suffix.lower() in (".xlsx", ".xlsm", ".xls"):
        sheets = pd.read_excel(path, sheet_name=None, header=None, nrows=max_header_row)
        chosen, seen = None, []
        for name, frame in sheets.items():
            for r in range(len(frame)):
                vals = [_norm_header(v) for v in frame.iloc[r].tolist() if pd.notna(v)]
                if any(v in _WELL_KEYS for v in vals):
                    chosen = (name, r)
                    break
            if chosen:
                break
            first = next((frame.iloc[r].dropna().astype(str).tolist() for r in range(len(frame))
                          if frame.iloc[r].notna().any()), [])
            seen.append(f"'{name}': first non-empty row {first[:8]}")
        if chosen is None:
            raise WellDataError(f"No sheet with a 'Well Name' header cell in the first {max_header_row} rows of {path}. "
                                f"Sheets: {'; '.join(seen) or 'none'}")
        meta["sheet"], meta["header_row"] = chosen
        raw = pd.read_excel(path, sheet_name=chosen[0], header=chosen[1])
        meta["reader"] = "pandas.read_excel"
    else:
        raw = pd.read_csv(path)
        meta["reader"] = "pandas.read_csv"
    rename = {}
    for col in raw.columns:
        key = _norm_header(col)
        if key in _HEADER_COLUMN_MAP:
            rename[col] = _HEADER_COLUMN_MAP[key]
        else:
            meta["unmapped_columns"].append(str(col))
    df = raw.rename(columns=rename).copy()
    if "well" not in df.columns:
        raise WellDataError(f"Could not find the well-name column in {path}")
    df = df[df["well"].notna()].copy()
    df["well"] = df["well"].astype(str).str.strip().str.lower()
    for col in ("rt_m", "water_depth_m", "td_m", "x", "y"):
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")
    for col in [c for c in df.columns if c.startswith("flag_")]:
        df[col] = df[col].map(_flag_value)
    meta["n_wells"] = int(len(df))
    return df.reset_index(drop=True), meta


