# 4. Time-depth tables (Petrel 'checkshot' exports and similar)
# =============================================================================
_TDR_COLUMN_MAP = {
    "MDKB": "md_kb_m", "MD": "md_kb_m", "MDRT": "md_kb_m",
    "TWT": "twt_ms", "TWTT": "twt_ms", "TIME": "twt_ms",
    "OWT": "owt_ms",
    "TVDSS": "tvdss_m", "TVD_SS": "tvdss_m", "Z": "z_unknown", "TVD": "tvd_kb_m",
}


@dataclass
class TimeDepthTable:
    well: str
    data: pd.DataFrame        # md_kb_m, twt_ms, tvdss_m (when present)
    meta: dict = field(default_factory=dict)


def parse_tdr_table(path: str | Path, well: str) -> TimeDepthTable:
    """Parse a time-depth table and record its provenance line and sampling pattern."""
    path = Path(path)
    lines = [l.rstrip() for l in path.read_text(encoding="utf-8", errors="replace").splitlines()]
    lines = [l for l in lines if l.strip()]
    meta: dict = {"path": str(path), "flags": [], "description_line": None}
    names: list[str] = []
    start = 0
    # Comment-header checkshots commonly declare one field per line, e.g.
    # #Checkshot / #TVDSS (m) / #TWT (ms), followed by two numeric columns.
    comment_names: list[str] = []
    comment_aliases = {"MDKB": "MDKB", "MD": "MDKB", "MDRT": "MDKB",
                       "TWT": "TWT", "TWTT": "TWT", "TIME": "TWT",
                       "TVDSS": "TVDSS", "TVD_SS": "TVDSS"}
    while start < len(lines) and lines[start].lstrip().startswith("#"):
        match = re.match(r"^\s*#\s*([A-Za-z_]+)(?:\s*\(([^)]+)\))?", lines[start])
        if match and match.group(1).upper() in comment_aliases:
            comment_names.append(comment_aliases[match.group(1).upper()])
            if match.group(2):
                meta.setdefault("column_units", {})[comment_names[-1]] = match.group(2).strip()
        start += 1
    if comment_names:
        names = comment_names
        meta["description_line"] = "comment-header table"
    elif start == 0 and not _is_numeric_row(lines[0]):
        meta["description_line"] = lines[0].strip()
        start = 1
        if len(lines) > 1 and lines[1].strip().isdigit():
            ncols = int(lines[1].strip())
            names = [lines[2 + i].strip() for i in range(ncols)]
            start = 2 + ncols
        else:
            while start < len(lines) and not _is_numeric_row(lines[start]):
                names += re.split(r"[\s,;]+", lines[start].strip())
                start += 1
    values = np.array([[float(v) for v in re.split(r"[\s,;]+", l.strip())] for l in lines[start:]
                       if _is_numeric_row(l)], dtype=float)
    if values.size == 0:
        raise WellDataError(f"No numeric rows in time-depth table {path}")
    if not names or len(names) != values.shape[1]:
        if values.shape[1] == 2:
            meta["flags"].append("column_names_missing_or_mismatched -> assumed TVDSS TWT")
            names = ["TVDSS", "TWT"]
        else:
            meta["flags"].append("column_names_missing_or_mismatched -> assumed MDKB TWT TVDSS")
            names = ["MDKB", "TWT", "TVDSS"][: values.shape[1]]
    mapped = [_TDR_COLUMN_MAP.get(n.upper(), n.lower()) for n in names]
    df = pd.DataFrame(values, columns=mapped)
    if "owt_ms" in df.columns and "twt_ms" not in df.columns:
        df["twt_ms"] = 2.0 * df["owt_ms"]
        meta["flags"].append("one_way_time_converted_to_TWT")
    meta["columns_in_file"] = names
    meta["units_assumed"] = "depth m, time ms (file states no units; Petrel export default)"

    desc = meta["description_line"] or ""
    m = re.search(r"generated by (\S+) on (.+)$", desc)
    meta["generated_by"] = m.group(1) if m else None
    meta["generated_on"] = m.group(2).strip() if m else None
    meta["looks_like_team_export"] = bool(m)

    if "twt_ms" in df.columns:
        dt = np.diff(df["twt_ms"].to_numpy())
        meta["n_rows"] = int(len(df))
        meta["twt_range_ms"] = [float(df["twt_ms"].min()), float(df["twt_ms"].max())]
        nonzero = dt[dt > 0]
        if len(nonzero) > 5 and np.ptp(nonzero[1:]) < 1e-6:
            meta["sampling_pattern"] = f"regular TWT step {nonzero[1]:.3f} ms (resampled function)"
        else:
            meta["sampling_pattern"] = "irregular stations"
        if np.any(dt <= 0):
            meta["flags"].append(f"twt_not_strictly_increasing_rows={int((dt <= 0).sum())}")
    if "tvdss_m" in df.columns:
        meta["tvdss_range_m"] = [float(df["tvdss_m"].min()), float(df["tvdss_m"].max())]
        if np.any(np.diff(df["tvdss_m"].to_numpy()) <= 0):
            meta["flags"].append("tvdss_not_strictly_increasing")
        if "md_kb_m" in df.columns:
            first = df.iloc[0]
            meta["implied_datum_elevation_m"] = float(first["md_kb_m"] - first["tvdss_m"])
    return TimeDepthTable(well=well, data=df, meta=meta)


def _is_numeric_row(line: str) -> bool:
    parts = re.split(r"[\s,;]+", line.strip())
    if not parts or parts == [""]:
        return False
    try:
        [float(p) for p in parts]
        return True
    except ValueError:
        return False


