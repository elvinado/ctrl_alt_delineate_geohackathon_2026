def _load_full_seismic_path(ctx) -> "Path | None":
    """Resolve full stack from Stage 00's registered-dataset inventory."""
    inventory = ctx.run.run_dir / "00_inventory" / "tables" / "seismic_volume_inventory.csv"
    if not inventory.is_file():
        return None
    frame = pd.read_csv(inventory)
    if not {"volume", "path", "exists"}.issubset(frame.columns):
        return None
    rows = frame.loc[frame["volume"].astype(str).str.casefold() == "full"]
    if rows.empty:
        return None
    row = rows.iloc[0]
    exists = row["exists"]
    if isinstance(exists, str):
        exists = exists.strip().casefold() in {"true", "1", "yes"}
    path_value = str(row["path"]).strip()
    if not bool(exists) or not path_value:
        return None
    path = Path(path_value).expanduser()
    if not path.is_file():
        return None
    ctx.add_input(path, "upstream:registered_full_stack")
    return path


def _synthetic_tie(ctx, w, a, traj, tz, geom, full_path, cfg):
    """Build a synthetic from DT+RHOB and correlate it with the full stack along the well path."""
    scfg = cfg_get(cfg, "synthetic", {}) or {}
    las = read_las(a.get("las_file"), w)
    fam = {c["mnemonic"]: classify_curve(c["mnemonic"]) for c in las.curves[1:]}
    dt_m = next(m for m, f in fam.items() if f == "DT")
    rho_m = next(m for m, f in fam.items() if f == "RHOB")
    unit = {c["mnemonic"]: c["unit"] for c in las.curves}
    vp, vp_unit = sonic_to_vp(las.data[dt_m].to_numpy(), unit.get(dt_m))
    rho, rho_unit = density_to_kgm3(las.data[rho_m].to_numpy(), unit.get(rho_m))
    ai = vp * rho
    path = traj.at_md(las.depth_m)
    twt = tz.twt(path["tvdss_m"].to_numpy())
    ok = np.isfinite(ai) & np.isfinite(twt) & (path["tvdss_m"].to_numpy() >= 0)
    if ok.sum() < 50:
        raise ValueError("fewer than 50 samples with valid DT, RHOB and TWT")
    t_grid, ai_t = impedance_in_time(twt[ok], ai[ok], 1.0)
    rc = reflectivity(ai_t)
    order = np.argsort(twt[ok])
    xs = np.interp(t_grid, twt[ok][order], path["x"].to_numpy()[ok][order])
    ys = np.interp(t_grid, twt[ok][order], path["y"].to_numpy()[ok][order])
    with SegyFile(full_path, cfg_get(cfg, "seismic.byte_locations", {})) as sgy:
        ext = sgy.extract_along_path(geom, xs, ys, t_grid)
    obs = ext["values"]
    mode = str(scfg.get("wavelet_mode", "statistical_ricker"))
    spec = dominant_frequency(obs, 1.0)
    f_peak = float(scfg.get("ricker_peak_hz")) if mode == "fixed_ricker" else spec["peak_hz"]
    if not np.isfinite(f_peak) or f_peak <= 0:
        raise ValueError("could not estimate a dominant frequency from the observed trace")
    _, wav = ricker(f_peak, 1.0, float(scfg.get("wavelet_length_ms", 128)))
    syn = np.convolve(rc, wav, mode="same")
    dec = max(1, int(round(geom.dt_ms)))
    corr = lagged_correlation(syn[::dec], obs[::dec], geom.dt_ms, float(scfg.get("max_lag_ms", 40)))
    thr = float(scfg.get("cc_threshold_tied", 0.6))
    tied = bool(np.isfinite(corr["cc_best"]) and abs(corr["cc_best"]) >= thr)
    result = {"synthetic_possible": True, "synthetic_reason": "",
              "wavelet": f"zero-phase Ricker {f_peak:.1f} Hz ({mode})", "dt_curve": f"{dt_m} [{vp_unit}]",
              "rho_curve": f"{rho_m} [{rho_unit}]", "dominant_freq_hz": spec["peak_hz"],
              "band_low_hz": spec["band_low_hz"], "band_high_hz": spec["band_high_hz"],
              "best_lag_ms": corr["best_lag_ms"], "cc_best": corr["cc_best"], "cc_zero_lag": corr["cc_zero_lag"],
              "polarity": corr["polarity"], "max_trace_offset_xy": float(np.nanmax(ext["offset_xy"])),
              "cc_threshold_for_tied": thr, "synthetic_tied": tied}
    events = []
    for k, idx in enumerate(sorted(np.argsort(-np.abs(rc))[:8])):
        lo, hi = max(0, idx - 20), min(len(obs), idx + 21)
        seg = obs[lo:hi]
        if np.isfinite(seg).any():
            j = lo + int(np.nanargmax(np.abs(seg)))
            events.append({"well": w, "event": k + 1, "twt_synthetic_ms": float(t_grid[idx]),
                           "twt_observed_peak_ms": float(t_grid[j]), "shift_ms": float(t_grid[j] - t_grid[idx]),
                           "rc": float(rc[idx]), "not_available_reason": ""})
    _figure_synthetic(ctx, w, t_grid, ai_t, rc, syn, obs, corr, result)
    return result, events


