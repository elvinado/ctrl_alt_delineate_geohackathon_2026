"""Stage 01 - trajectories, time-depth (T-Z) functions, velocity QC, synthetic ties.

What happens, per well
----------------------
1. **Trajectory**: deviation survey + header (RT, surface X/Y) -> minimum
   curvature -> TVD below RT -> TVDSS (m below MSL) -> X/Y along the hole.
   Checked against the MD->TVDSS columns of any T-Z table (independent export).
2. **Regional T-Z model** for wells without their own table.  Candidates are
   fitted to all T-Z table wells: origin-anchored polynomials (degrees 2-5,
   "polynomial T-Z curves") and the physical linear-velocity law
   V(z) = V0 + k z.  Each is scored by leave-one-well-out (LOWO) RMS **and** a
   physical-extrapolation check down to the deepest depth any well needs
   (TWT increasing, velocity in bounds, no velocity turnover where no data
   exist).  Rule (declared in the config before seeing results): pick the
   lowest mean LOWO RMS among physically valid candidates.
3. **T-Z source per well** (written into every output row):

   ===========================  =================================================
   tie_status                   meaning
   ===========================  =================================================
   measured_checkshot           T-Z table YOU approved in the config as a
                                measured checkshot (none by default)
   unvalidated                  a T-Z table exists (team export) but provenance
                                is unverified; used as the well's local T-Z
   provisional_polynomial       no table; regional polynomial selected
   provisional_linear_velocity  no table; regional V0 + k z law selected
   synthetic_tied               synthetic from DT+RHOB matched the real full
                                stack (|CC| >= threshold) - only where logs permit
   failed                       no usable T-Z -> labelled extraction blocked
   ===========================  =================================================

4. **Velocity QC**: Vint = 2000 / (dTWT_ms/dz_m) of the function actually used.
   Non-positive slopes (non-physical) are separated from "undefined" values
   caused by sparse control.  Non-physical slopes or out-of-bound velocities
   block that well's labelled extraction until reviewed.
5. **Synthetic tie** where DT and RHOB exist and the full stack is readable;
   otherwise a NOT AVAILABLE panel listing the exact reasons.

Provenance note (2026-11-03 inspection): the organiser well list marks
checkshots *not available*; the ``*_CS.txt`` files say "generated by
apgce_team_10 on Wed Oct 14 2026".  They are UNVERIFIED team exports unless
approved in ``checkshot_provenance``.
"""

