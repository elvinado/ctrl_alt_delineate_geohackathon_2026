def _figure_all_vint(ctx, tie_rows, tables, regional, poly_cmp, bounds, smooth_win, lowo, zt, fitter, chosen):
    import matplotlib.pyplot as plt

    fig, (ax, ax2) = plt.subplots(1, 2, figsize=(16, 9), gridspec_kw={"width_ratios": [1.3, 1]})
    zmax_all = max([r.get("tvdss_max_needed_m", 0) or 0 for r in tie_rows] + [100])
    zg = np.arange(10.0, zmax_all + 5, 5.0)
    ax.axvspan(bounds[0], bounds[1], color=STATUS["good"], alpha=0.05, lw=0)
    colors = [SERIES[0], SERIES[2], SERIES[6]]
    order = sorted(tables)
    for k, w in enumerate(order):
        d = tables[w].data
        sv = station_interval_velocities(d["tvdss_m"], d["twt_ms"])
        c = colors[k % len(colors)]
        ax.scatter(sv["vint_ms"], sv["z_mid_m"], s=5, color=c, alpha=0.35)
        vs = smoothed_interval_velocity(d["tvdss_m"], d["twt_ms"], zg, smooth_win)
        ax.plot(vs, zg, color=c, lw=2.2)
        last = np.flatnonzero(np.isfinite(vs))
        if last.size:
            ax.annotate(w, (vs[last[-1]], zg[last[-1]]), xytext=(6, 0), textcoords="offset points",
                        color=c, fontweight="bold")
    if regional is not None:
        ax.plot(regional.vint(zg), zg, color=SERIES[1], ls="--", lw=2.2, label=f"selected regional: {chosen}")
    if poly_cmp is not None and poly_cmp is not regional:
        ax.plot(poly_cmp.vint(zg), zg, color=TEXT_2, ls="-.", lw=1.3,
                label=f"{poly_cmp.name} (comparison; note behaviour below its fit range)")
    if regional is not None:
        ax.axhline(regional.z_support[1], color=TEXT_2, lw=0.8, ls=":")
    ax.plot([], [], color=TEXT_2, lw=2.2, label=f"T-Z tables, trend over {smooth_win:g} m (dots: raw stations)")
    ax.set_xlim(1000, 6500)
    ax.set_ylim(zg.max() * 1.02, 0)
    ax.set_xlabel("interval velocity (m/s) = 2000 / (dTWT_ms/dz_m)")
    ax.set_ylabel("TVDSS (m below MSL)")
    ax.set_title(f"Interval velocity vs depth (shaded = plausible {bounds[0]:.0f}-{bounds[1]:.0f} m/s)")
    ax.legend(loc="lower left")
    if len(lowo) and "rms_ms" in lowo and lowo["rms_ms"].notna().any() and fitter is not None:
        for _, rr in lowo.iterrows():
            hold = rr["holdout_well"]
            others = [w for w in zt if w != hold]
            zz = np.concatenate([zt[w][0] for w in others])
            tt = np.concatenate([zt[w][1] for w in others])
            ww = np.concatenate([np.full(len(zt[w][0]), 1.0 / len(zt[w][0])) for w in others])
            model = fitter(zz, tt, ww, others)
            z, t = zt[hold]
            sel = z > 0
            c = colors[order.index(hold) % len(colors)] if hold in order else TEXT_2
            ax2.plot(model.twt(z[sel]) - t[sel], z[sel], color=c, lw=2,
                     label=f"{hold}: RMS {rr['rms_ms']:.1f} ms, bias {rr['bias_ms']:+.1f} ms, max {rr['max_abs_ms']:.0f} ms")
        ax2.axvline(0, color=TEXT_2, lw=0.8)
        for lim in (-4, 4):
            ax2.axvline(lim, color=TEXT_2, lw=0.6, ls=":")
        ax2.set_ylim(zg.max() * 1.02, 0)
        ax2.set_xlabel("predicted - table TWT (ms)   [dotted: +-1 seismic sample of 4 ms]")
        ax2.set_ylabel("TVDSS (m)")
        ax2.set_title(f"Leave-one-well-out error of the selected model ({chosen})")
        ax2.legend(loc="lower left")
    else:
        ax2.set_axis_off()
        ax2.text(0.5, 0.5, "Leave-one-well-out:\nNOT AVAILABLE\n(needs >= 2 T-Z table wells)", ha="center",
                 va="center", fontsize=12, color=STATUS["critical"], fontweight="bold")
    footer(fig, DATUM_NOTE + " Dotted horizontal line: deepest T-Z control.")
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    ctx.save_figure(fig, "all_wells_interval_velocity_vs_tvdss.png",
                    "Interval velocity vs TVDSS (tables, selected model, polynomial comparison) + LOWO error",
                    required=True, multipanel=True)


def _figure_comparison(ctx, tables, regional, zt, fitter, chosen):
    import matplotlib.pyplot as plt

    if not tables or regional is None:
        fig = not_available_figure("T-Z table vs provisional regional model", [
            "needs at least one T-Z table and a fitted regional model"])
        ctx.save_figure(fig, "measured_vs_provisional_comparison.png", "NOT AVAILABLE", required=True)
        return
    wells = sorted(tables)
    fig, axes = plt.subplots(2, len(wells), figsize=(max(16, 7 * len(wells)), 11), squeeze=False)
    for j, w in enumerate(wells):
        d = tables[w].data
        z, t = d["tvdss_m"].to_numpy(), d["twt_ms"].to_numpy()
        sel = z > 0
        ax = axes[0, j]
        ax.plot(regional.twt(z[sel]) - t[sel], z[sel], color=SERIES[1], ls="--", lw=2,
                label=f"{chosen} fitted to all table wells (incl. {w})")
        others = [x for x in zt if x != w]
        if others and fitter is not None:
            zz = np.concatenate([zt[x][0] for x in others])
            tt = np.concatenate([zt[x][1] for x in others])
            ww = np.concatenate([np.full(len(zt[x][0]), 1.0 / len(zt[x][0])) for x in others])
            model = fitter(zz, tt, ww, others)
            ax.plot(model.twt(z[sel]) - t[sel], z[sel], color=SERIES[0], lw=2, label=f"LOWO: fitted without {w}")
        for lim in (-4, 4):
            ax.axvline(lim, color=TEXT_2, lw=0.6, ls=":")
        ax.axvline(0, color=TEXT_2, lw=0.8)
        ax.invert_yaxis()
        ax.set_xlabel("model - table TWT (ms)   [dotted: +-1 sample]")
        ax.set_ylabel("TVDSS (m)")
        ax.set_title(f"{w}: TWT residual vs depth")
        ax.legend(loc="lower left")
        ax2 = axes[1, j]
        resid = tables[w].meta.get("tvdss_residual")
        if resid is not None and "md_kb_m" in d:
            ax2.scatter(resid * 100.0, d["md_kb_m"], s=12, color=SERIES[0])
            ax2.axvline(0, color=TEXT_2, lw=0.8)
            ax2.invert_yaxis()
            ax2.set_xlabel("our TVDSS - table TVDSS (cm)")
            ax2.set_ylabel("MD below RT (m)")
            ax2.set_title(f"{w}: trajectory & datum consistency (max |d| = {np.nanmax(np.abs(resid)) * 100:.1f} cm)")
        else:
            ax2.set_axis_off()
    fig.suptitle("T-Z tables (team exports, provenance unverified) vs the provisional regional model", fontsize=12,
                 fontweight="bold")
    footer(fig, DATUM_NOTE + " Bottom row: the table's own MD->TVDSS vs our independent minimum-curvature path.")
    fig.tight_layout(rect=(0, 0.03, 1, 0.96))
    ctx.save_figure(fig, "measured_vs_provisional_comparison.png",
                    "T-Z table vs regional model residuals (all-well and LOWO) + trajectory/datum consistency",
                    required=True, multipanel=True)


