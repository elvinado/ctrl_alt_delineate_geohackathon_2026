def _coef_row(model, name, resid) -> dict:
    if isinstance(model, LinearVelocityTZ):
        row = {"model_name": name, "source_type": "regional_linear_velocity", "direction": "TWT_ms = f(TVDSS_m)",
               "form": "TWT = (2000/k) * ln(1 + k*TVDSS/V0) ; V(z) = V0 + k*z ; anchored TWT(0)=0 at MSL",
               "coefficient_order": "parameters V0 (m/s), k (1/s)", "degree": "n/a",
               "v0_ms": model.v0, "k_per_s": model.k}
    else:
        row = {"model_name": name, "source_type": "regional_polynomial", "direction": "TWT_ms = f(TVDSS_m)",
               "form": "TWT = sum_{k=1..d} c_k * (TVDSS/scale)^k ; anchored TWT(0)=0 at MSL",
               "coefficient_order": "ascending powers k=1..d (no constant term)", "degree": model.degree,
               "scale_m": model.scale}
        for k, c in enumerate(model.coeffs, start=1):
            row[f"c{k}_normalised_ms"] = c
        for k, c in enumerate(model.physical_coefficients(), start=1):
            row[f"a{k}_physical_ms_per_m^{k}"] = c
    row.update(fit_wells=",".join(model.fit_wells), fit_domain_tvdss_min_m=model.z_support[0],
               fit_domain_tvdss_max_m=model.z_support[1], weighting="equal total weight per well")
    if resid is not None and len(resid):
        row.update(rms_residual_ms=float(np.sqrt(np.mean(resid ** 2))),
                   max_abs_residual_ms=float(np.max(np.abs(resid))))
    return row


def _load_full_geometry(ctx) -> SurveyGeometry | None:
    path = ctx.run.run_dir / "00_inventory" / "tables" / "geometry" / "full_geometry.npz"
