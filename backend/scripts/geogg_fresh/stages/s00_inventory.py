"""Stage 00 - locate, open and register every input.

Purpose
-------
Before any science we must know *exactly* what data exists, what is inside it
and what is missing.  This stage opens every file (not just checks its name):

* well header workbook  -> RT elevation, TD, surface X/Y, organiser availability flags
* 13 LAS files          -> every curve mnemonic, unit, depth index, missing fraction,
                           physical-range flags, and a *screening* of the
                           provider's hydrocarbon-indicator curves (PS_GIP/PS_OIP)
* 13 deviation surveys  -> column order from the header, nulls, gaps, max inclination
* time-depth tables     -> provenance line ("generated by ..."), sampling pattern
* historic products     -> existence + hash only (READ-ONLY reference)
* 9 SEG-Y volumes       -> binary/trace headers, sample rate, start time, IL/XL
                           ranges, XY transform, bin size, line azimuths, amplitude
                           statistics and registration against the full stack

Gate (AGENTS.md): all 13 wells accounted for, missing sources explicitly marked,
seismic geometry/datum identified - otherwise CONDITIONAL with the issue named.
"""

