def _findings_text(avail, vol_df, n_tz, approved) -> str:
    lines = []
    gen = avail.get("tz_table_generated_by", pd.Series(dtype=object)).dropna().unique()
    if n_tz:
        lines.append(f"- {n_tz} time-depth table(s) found; header line says generated by {list(gen)}. The organiser "
                     f"well list marks checkshots NOT available, so they are treated as UNVERIFIED team exports "
                     f"(approve in config `checkshot_provenance.approved_as_measured` only after review).")
    if "deviation_column_order" in avail:
        orders = avail["deviation_column_order"].dropna().unique()
        lines.append(f"- Deviation column order read from file headers: {list(orders)} (MD, AZIMUTH, INCLINATION).")
    if "deviation_n_null_rows" in avail and avail["deviation_n_null_rows"].fillna(0).sum() > 0:
        bad = avail[avail["deviation_n_null_rows"].fillna(0) > 0]["well"].tolist()
        lines.append(f"- Null (-999.25) direction rows in deviation surveys of {bad}; direction held from the "
                     f"previous station and flagged.")
    deviation_flags = avail["deviation_flags"] if "deviation_flags" in avail else pd.Series("", index=avail.index)
    vertical = avail[deviation_flags.fillna("").str.contains("all_inclinations_zero")]
    if len(vertical):
        lines.append(f"- All-zero inclination surveys (vertical or placeholder): {vertical['well'].tolist()}.")
    lines.append("- Coordinates: CRS undisclosed (randomised). Nothing is reprojected; X/Y are used as given.")
    if not vol_df.get("exists", pd.Series(dtype=bool)).fillna(False).any():
        lines.append("- SEG-Y volumes were not reachable in this execution; geometry checks pending.")
    return "\n".join(lines)
