"""Time-depth (T-Z) functions and interval-velocity QC.

The physics in one paragraph
----------------------------
Seismic is recorded in two-way time (TWT, ms); logs are in depth.  A T-Z
function maps depth below the seismic datum (here mean sea level, so TVDSS in m,
positive down) to TWT.  Its slope gives the **interval velocity**::

    one-way time t = TWT/2000  [s]   ->   Vint = dz/dt = 2000 / (dTWT_ms / dz_m)   [m/s]

A physically valid T-Z function is **strictly increasing** (TWT grows with
depth) and gives velocities in a plausible range (water ~1480-1540 m/s,
shallow clastics ~1600-2500 m/s, deep compacted rocks ~3000-5500 m/s).  Every
function built here is checked against exactly these rules and flagged - never
silently "fixed".

Sources of T-Z in this project (all labelled in the outputs)
------------------------------------------------------------
``tdr_table``              a time-depth table exported for a well (here: files
                           ``<well>_CS.txt`` "generated by apgce_team_10"; the
                           organiser's well list marks checkshots NOT available,
                           so these are *not* treated as measured checkshots
                           unless you approve them in the config).
``regional_polynomial``    TWT = sum_k c_k (z/s)^k, k = 1..d, fitted to the TDR
                           tables (anchored at TWT=0 at MSL).  Provisional.
``historic_polynomial``    the team's earlier ``phase2_polynomial_models.csv`` -
                           evaluated ONLY when you tell the config how its
                           coefficients are ordered and what x/y are.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import pandas as pd


class TZError(RuntimeError):
    pass


# =============================================================================
# Base class
# =============================================================================
@dataclass
class TZFunction:
    name: str
    source_type: str
    provenance: str
    z_support: tuple[float, float]           # depth range directly supported by data (m TVDSS)
    max_extrapolation_m: float = 300.0
    flags: list[str] = field(default_factory=list)

    def twt(self, z) -> np.ndarray:          # pragma: no cover - implemented by subclasses
        raise NotImplementedError

    def dtwt_dz(self, z) -> np.ndarray:      # pragma: no cover
        raise NotImplementedError

    def vint(self, z) -> np.ndarray:
        """Interval velocity (m/s) = 2000 / (dTWT/dz); NaN where the slope is not positive."""
        slope = np.asarray(self.dtwt_dz(z), dtype=float)
        with np.errstate(divide="ignore", invalid="ignore"):
            return np.where(slope > 0, 2000.0 / slope, np.nan)

    def extrapolation_m(self, z) -> np.ndarray:
        """Distance (m) outside the supported depth range (0 inside)."""
        z = np.asarray(z, dtype=float)
        lo, hi = self.z_support
        return np.where(z < lo, lo - z, np.where(z > hi, z - hi, 0.0))


# =============================================================================
# 1. Table-based T-Z (interpolates the stations of a time-depth table)
# =============================================================================
class TableTZ(TZFunction):
    """Linear interpolation of (TVDSS, TWT) stations.

    Below the deepest station the function continues with the mean interval
    velocity of the deepest ``tail_window_m`` metres (flagged as extrapolation).
    """

    def __init__(self, name, tvdss_m, twt_ms, provenance, source_type="tdr_table",
                 tail_window_m=150.0, max_extrapolation_m=300.0):
        z = np.asarray(tvdss_m, dtype=float)
        t = np.asarray(twt_ms, dtype=float)
        order = np.argsort(z, kind="stable")
        z, t = z[order], t[order]
        flags = []
        if np.any(np.diff(z) <= 0):
            flags.append("duplicate_or_reversed_depths")
        if np.any(np.diff(t) <= 0):
            flags.append("TWT_not_strictly_increasing_with_depth (non-physical; blocks labelled extraction)")
        super().__init__(name, source_type, provenance, (float(z.min()), float(z.max())),
                         max_extrapolation_m, flags)
        self.z, self.t = z, t
        tail = z >= z.max() - tail_window_m
        if tail.sum() >= 2 and np.ptp(t[tail]) > 0:
            slope = np.polyfit(z[tail], t[tail], 1)[0]
        else:
            slope = (t[-1] - t[0]) / max(z[-1] - z[0], 1e-6)
        self.tail_slope = float(slope)                 # ms per m

    def twt(self, z):
        z = np.asarray(z, dtype=float)
        out = np.interp(z, self.z, self.t)
        deep = z > self.z[-1]
        out = np.where(deep, self.t[-1] + (z - self.z[-1]) * self.tail_slope, out)
        return np.where(z < self.z[0], np.nan, out)

    def dtwt_dz(self, z):
        z = np.asarray(z, dtype=float)
        seg_slope = np.diff(self.t) / np.diff(self.z)
        idx = np.clip(np.searchsorted(self.z, z, side="right") - 1, 0, len(seg_slope) - 1)
        out = seg_slope[idx]
        return np.where(z > self.z[-1], self.tail_slope, out)


# =============================================================================
# 2. Polynomial T-Z anchored at the datum (TWT = 0 at TVDSS = 0)
# =============================================================================
class PolynomialTZ(TZFunction):
    """TWT_ms = sum_{k=1..d} c_k * (z / scale)^k  with z = TVDSS in metres.

    *Coefficient order is ascending powers, starting at k = 1* (no constant term
    because the function is anchored at the datum).  Depth is normalised by
    ``scale`` only for numerical stability; inputs and outputs are physical
    (m, ms, m/s).  ``physical_coefficients()`` returns a_k with
    TWT_ms = sum a_k * z^k for readers who prefer unnormalised numbers.
    """

    def __init__(self, name, coeffs, scale, z_support, provenance, source_type="regional_polynomial",
                 max_extrapolation_m=300.0, fit_wells=()):
        super().__init__(name, source_type, provenance, z_support, max_extrapolation_m, [])
        self.coeffs = np.asarray(coeffs, dtype=float)
        self.scale = float(scale)
        self.fit_wells = tuple(fit_wells)

    @property
    def degree(self) -> int:
        return len(self.coeffs)

    def twt(self, z):
        u = np.asarray(z, dtype=float) / self.scale
        return sum(c * u ** (k + 1) for k, c in enumerate(self.coeffs))

    def dtwt_dz(self, z):
        u = np.asarray(z, dtype=float) / self.scale
        return sum((k + 1) * c * u ** k for k, c in enumerate(self.coeffs)) / self.scale

    def physical_coefficients(self) -> np.ndarray:
        return np.array([c / self.scale ** (k + 1) for k, c in enumerate(self.coeffs)])


def fit_anchored_polynomial(z, t, degree=3, weights=None, name="regional_polynomial",
                            provenance="", max_extrapolation_m=300.0, fit_wells=()) -> PolynomialTZ:
    """Weighted least-squares fit of an origin-anchored polynomial TWT(z)."""
    z = np.asarray(z, dtype=float)
    t = np.asarray(t, dtype=float)
    ok = np.isfinite(z) & np.isfinite(t) & (z > 0)
    z, t = z[ok], t[ok]
    if len(z) < degree + 2:
        raise TZError(f"Need at least {degree + 2} points to fit degree {degree}; got {len(z)}")
    w = np.ones_like(z) if weights is None else np.asarray(weights, dtype=float)[ok]
    scale = float(z.max())
    u = z / scale
    design = np.column_stack([u ** (k + 1) for k in range(degree)])
    sw = np.sqrt(w)
    coeffs, *_ = np.linalg.lstsq(design * sw[:, None], t * sw, rcond=None)
    return PolynomialTZ(name, coeffs, scale, (0.0, float(z.max())), provenance,
                        max_extrapolation_m=max_extrapolation_m, fit_wells=fit_wells)


