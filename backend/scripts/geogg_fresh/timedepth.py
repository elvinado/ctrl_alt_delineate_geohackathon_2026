def inspect_table_file(path) -> dict:
    """Describe an unknown CSV (columns, first rows) without interpreting it."""
    df = pd.read_csv(path)
    return {"path": str(path), "n_rows": int(len(df)), "columns": list(map(str, df.columns)),
            "head": df.head(5).to_dict(orient="records")}


class HistoricPolyTZ(TZFunction):
    """Evaluate a polynomial from the historic CSV using an EXPLICIT mapping.

    mapping keys: ``coefficient_columns`` (list, in file order), ``coefficient_order``
    ('ascending' = c0 + c1 x + ..., 'descending' = numpy.polyfit order),
    ``independent_variable`` ('tvdss_m' or 'twt_ms'), ``x_offset_column`` /
    ``x_scale_column`` (optional normalisation x' = (x - offset) / scale).
    If x is TWT (depth = f(TWT)), the function is inverted numerically on a grid.
    """

    def __init__(self, name, row: dict, mapping: dict, provenance: str, z_eval_max=6000.0):
        coeffs = np.array([float(row[c]) for c in mapping["coefficient_columns"]])
        if str(mapping.get("coefficient_order", "ascending")).lower().startswith("desc"):
            coeffs = coeffs[::-1]
        self.c = coeffs
        self.offset = float(row[mapping["x_offset_column"]]) if mapping.get("x_offset_column") else 0.0
        self.xscale = float(row[mapping["x_scale_column"]]) if mapping.get("x_scale_column") else 1.0
        self.x_is_depth = str(mapping.get("independent_variable", "tvdss_m")).lower().startswith("tvd")
        lo = float(row[mapping["domain_min_column"]]) if mapping.get("domain_min_column") else 0.0
        hi = float(row[mapping["domain_max_column"]]) if mapping.get("domain_max_column") else np.nan
        flags = []
        if self.x_is_depth:
            support = (lo, hi if np.isfinite(hi) else z_eval_max)
        else:   # depth = f(TWT): build a dense lookup and invert
            tgrid = np.linspace(lo, hi if np.isfinite(hi) else 5000.0, 20001)
            zgrid = self._poly(tgrid)
            if np.any(np.diff(zgrid) <= 0):
                flags.append("depth(TWT) not monotonic - inversion unreliable")
            self._tgrid, self._zgrid = tgrid, zgrid
            support = (float(np.nanmin(zgrid)), float(np.nanmax(zgrid)))
        if not np.isfinite(hi):
            flags.append("fit domain not stated in file - support range assumed")
        super().__init__(name, "historic_polynomial", provenance, support, 300.0, flags)

    def _poly(self, x):
        u = (np.asarray(x, dtype=float) - self.offset) / self.xscale
        return sum(c * u ** k for k, c in enumerate(self.c))

    def twt(self, z):
        if self.x_is_depth:
            return self._poly(z)
        return np.interp(np.asarray(z, dtype=float), self._zgrid, self._tgrid, left=np.nan, right=np.nan)

    def dtwt_dz(self, z, dz=0.5):
        z = np.asarray(z, dtype=float)
        return (self.twt(z + dz) - self.twt(z - dz)) / (2 * dz)
