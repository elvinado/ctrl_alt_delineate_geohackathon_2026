def station_interval_velocities(tvdss_m, twt_ms) -> pd.DataFrame:
    """Raw station-to-station interval velocities (noisy by nature: 0.1 ms over 15 m ~ 1%)."""
    z = np.asarray(tvdss_m, dtype=float)
    t = np.asarray(twt_ms, dtype=float)
    dz, dt = np.diff(z), np.diff(t)
    with np.errstate(divide="ignore", invalid="ignore"):
        v = np.where(dt > 0, 2000.0 * dz / dt, np.nan)
    return pd.DataFrame({"z_top_m": z[:-1], "z_base_m": z[1:], "z_mid_m": 0.5 * (z[:-1] + z[1:]),
                         "dz_m": dz, "dtwt_ms": dt, "vint_ms": v, "non_positive_dt": dt <= 0})


def smoothed_interval_velocity(tvdss_m, twt_ms, z_eval, window_m=100.0) -> np.ndarray:
    """Interval velocity from a local straight-line fit of TWT vs depth (+-window/2)."""
    z = np.asarray(tvdss_m, dtype=float)
    t = np.asarray(twt_ms, dtype=float)
    out = np.full(len(z_eval), np.nan)
    for i, zc in enumerate(np.asarray(z_eval, dtype=float)):
        sel = np.abs(z - zc) <= window_m / 2
        if sel.sum() >= 3 and np.ptp(z[sel]) > 0:
            slope = np.polyfit(z[sel], t[sel], 1)[0]
            out[i] = 2000.0 / slope if slope > 0 else np.nan
    return out


def velocity_qc(z, vint, bounds=(1400.0, 6500.0), max_jump_ratio=1.6, slope=None) -> dict:
    """Summarise an interval-velocity profile and flag non-physical behaviour.

    ``slope`` (dTWT/dz of the function actually used) lets us separate two very
    different things that both appear as NaN velocity:
      * non-positive slope  -> TWT does not increase with depth -> NON-PHYSICAL
      * undefined velocity  -> not enough control points (e.g. sparse shallow
        stations) -> a data-coverage note, not a physics failure.
    """
    z = np.asarray(z, dtype=float)
    v = np.asarray(vint, dtype=float)
    finite = np.isfinite(v)
    nonpos = np.zeros(v.shape, dtype=bool) if slope is None else (np.asarray(slope, dtype=float) <= 0)
    undefined = ~finite & ~nonpos
    flags = []
    if nonpos.any():
        flags.append(f"NON_PHYSICAL_non_positive_dTWT_dz_samples={int(nonpos.sum())}")
    if undefined.any():
        flags.append(f"undefined_velocity_samples={int(undefined.sum())} (insufficient control, not non-physical)")
    low = int((v[finite] < bounds[0]).sum())
    high = int((v[finite] > bounds[1]).sum())
    if low:
        flags.append(f"velocity_below_{bounds[0]:.0f}_samples={low}")
    if high:
        flags.append(f"velocity_above_{bounds[1]:.0f}_samples={high}")
    vf = v[finite]
    jumps = vf[1:] / vf[:-1] if len(vf) > 1 else np.array([1.0])
    max_jump = float(np.nanmax(np.maximum(jumps, 1.0 / jumps))) if len(jumps) else 1.0
    if max_jump > max_jump_ratio:
        flags.append(f"velocity_jump_ratio={max_jump:.2f}>{max_jump_ratio} (station noise or real contrast)")
    decreasing = float(np.mean(jumps < 0.98)) if len(vf) > 1 else 0.0
    return {
        "n_samples": int(len(v)), "vint_min_ms": float(np.nanmin(v)) if finite.any() else np.nan,
        "vint_max_ms": float(np.nanmax(v)) if finite.any() else np.nan,
        "vint_median_ms": float(np.nanmedian(v)) if finite.any() else np.nan,
        "n_non_physical_slope": int(nonpos.sum()), "n_undefined_insufficient_control": int(undefined.sum()),
        "n_below_bound": low, "n_above_bound": high, "max_adjacent_jump_ratio": max_jump,
        "fraction_steps_velocity_decreasing": decreasing, "monotonic_twt": bool(not nonpos.any()),
        "flags": ";".join(flags),
    }


class LinearVelocityTZ(TZFunction):
    """Instantaneous velocity increasing linearly with depth: V(z) = V0 + k z.

    Integrating dt = dz / V(z) (one-way) gives the closed form::

        TWT_ms(z) = (2000 / k) * ln(1 + k z / V0)        (k -> 0:  TWT = 2000 z / V0)

    Two physically meaningful parameters (V0 in m/s at the datum, compaction
    gradient k in 1/s).  It is monotonic by construction and extrapolates with
    steadily increasing velocity - unlike free polynomials, whose derivative can
    turn over or explode outside the data.
    """

    def __init__(self, name, v0, k, z_support, provenance, max_extrapolation_m=300.0, fit_wells=()):
        super().__init__(name, "regional_linear_velocity", provenance, z_support, max_extrapolation_m, [])
        self.v0, self.k = float(v0), float(k)
        self.fit_wells = tuple(fit_wells)

    def twt(self, z):
        z = np.asarray(z, dtype=float)
        if abs(self.k) < 1e-9:
            return 2000.0 * z / self.v0
        return 2000.0 / self.k * np.log1p(self.k * z / self.v0)

    def dtwt_dz(self, z):
        return 2000.0 / (self.v0 + self.k * np.asarray(z, dtype=float))


def fit_linear_velocity(z, t, weights=None, name="regional_linear_velocity", provenance="",
                        max_extrapolation_m=300.0, fit_wells=()) -> LinearVelocityTZ:
    """Weighted least-squares fit of V0 and k (bounded to physically sensible ranges)."""
    from scipy.optimize import curve_fit

    z = np.asarray(z, dtype=float)
    t = np.asarray(t, dtype=float)
    ok = np.isfinite(z) & np.isfinite(t) & (z > 0)
    z, t = z[ok], t[ok]
    if len(z) < 4:
        raise TZError(f"Need at least 4 points to fit V0 + k z; got {len(z)}")
    w = np.ones_like(z) if weights is None else np.asarray(weights, dtype=float)[ok]

    def model(zz, v0, k):
        return 2000.0 / k * np.log1p(k * zz / v0)

    (v0, k), _ = curve_fit(model, z, t, p0=(1600.0, 0.5), sigma=1.0 / np.sqrt(w),
                           bounds=([1300.0, 1e-6], [3500.0, 3.0]), maxfev=20000)
    return LinearVelocityTZ(name, v0, k, (0.0, float(z.max())), provenance, max_extrapolation_m, fit_wells)


def physical_extrapolation_check(tz: TZFunction, z_needed_max: float, bounds=(1400.0, 6500.0)) -> dict:
    """Is the model still physical down to the deepest depth any well needs?

    Rules (declared before looking at results): TWT strictly increasing; velocity
    inside bounds; and - *only in the extrapolated part, where no data exist* -
    velocity must not decrease with depth (a decrease there is a curve-fitting
    artefact, not geological evidence).
    """
    zg = np.arange(5.0, max(z_needed_max, tz.z_support[1]) + 5.0, 5.0)
    slope = tz.dtwt_dz(zg)
    v = tz.vint(zg)
    beyond = zg > tz.z_support[1]
    ok_mono = bool(np.all(slope > 0))
    ok_bounds = bool(np.all((v >= bounds[0]) & (v <= bounds[1])))
    vb = v[beyond]
    ok_trend = bool(np.all(np.diff(vb) >= -1e-6)) if vb.size > 1 else True
    return {"z_checked_to_m": float(zg.max()), "twt_monotonic": ok_mono, "velocity_in_bounds": ok_bounds,
            "no_velocity_turnover_in_extrapolation": ok_trend, "vint_at_z_max_ms": float(v[-1]),
            "physically_valid": ok_mono and ok_bounds and ok_trend}


def leave_one_well_out(tables: dict[str, tuple[np.ndarray, np.ndarray]], degree=3, fitter=None) -> pd.DataFrame:
    """Fit a regional model without each well and predict that well.

    ``fitter(z, t, weights, fit_wells)`` returns a TZFunction; by default an
    origin-anchored polynomial of ``degree``.  With N wells this gives N honest
    transfer-error estimates (ms).  With fewer than 2 wells it returns an
    explanatory row instead of a fake number.
    """
    if fitter is None:
        def fitter(z, t, w, fw):
            return fit_anchored_polynomial(z, t, degree, w, fit_wells=fw)
    rows = []
    wells = sorted(tables)
    if len(wells) < 2:
        return pd.DataFrame([{"holdout_well": w, "fit_wells": "", "n_points": 0, "rms_ms": np.nan,
                              "bias_ms": np.nan, "max_abs_ms": np.nan,
                              "note": "LOWO impossible: fewer than 2 wells with T-Z tables"} for w in wells])
    for hold in wells:
        others = [w for w in wells if w != hold]
        z_fit = np.concatenate([tables[w][0] for w in others])
        t_fit = np.concatenate([tables[w][1] for w in others])
        weights = np.concatenate([np.full(len(tables[w][0]), 1.0 / len(tables[w][0])) for w in others])
        try:
            model = fitter(z_fit, t_fit, weights, others)
        except (TZError, RuntimeError, ValueError) as exc:
            rows.append({"holdout_well": hold, "fit_wells": ",".join(others), "n_points": 0,
                         "rms_ms": np.nan, "bias_ms": np.nan, "max_abs_ms": np.nan, "note": str(exc)})
            continue
        z, t = tables[hold]
        sel = z > 0
        resid = model.twt(z[sel]) - t[sel]
        inside = z[sel] <= model.z_support[1]
        rows.append({"holdout_well": hold, "fit_wells": ",".join(others), "n_points": int(sel.sum()),
                     "rms_ms": float(np.sqrt(np.mean(resid ** 2))), "bias_ms": float(np.mean(resid)),
                     "max_abs_ms": float(np.max(np.abs(resid))),
                     "fraction_points_extrapolated": float(1 - inside.mean()),
                     "note": "model fitted WITHOUT the held-out well"})
    return pd.DataFrame(rows)


def candidate_fitters(degrees=(2, 3, 4, 5), max_extrapolation_m=300.0) -> dict:
    """Name -> fitter(z, t, weights, fit_wells) for every regional model candidate."""
    out = {}
    for d in degrees:
        out[f"polynomial_deg{d}"] = (lambda dd: (lambda z, t, w, fw: fit_anchored_polynomial(
            z, t, dd, w, name=f"polynomial_deg{dd}", max_extrapolation_m=max_extrapolation_m, fit_wells=fw,
            provenance=f"degree-{dd} origin-anchored polynomial fitted to T-Z tables of {list(fw)}")))(d)
    out["linear_velocity"] = lambda z, t, w, fw: fit_linear_velocity(
        z, t, w, max_extrapolation_m=max_extrapolation_m, fit_wells=fw,
        provenance=f"V(z) = V0 + k z fitted to T-Z tables of {list(fw)}")
    return out


