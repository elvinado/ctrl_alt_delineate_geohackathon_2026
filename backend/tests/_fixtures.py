def write_segy(path, data, ils, xls, xs, ys, dt_us=4000, fmt=5, scalar=-100, delay_ms=0):
    """Write a minimal SEG-Y rev1 file (big-endian) with IL/XL/CDP-XY headers."""
    data = np.asarray(data, dtype=np.float32)
    n, ns = data.shape
    text = ("C01 GEOGG TEST FIXTURE - SOFTWARE TEST ONLY - NOT FIELD DATA".ljust(80) * 40).encode("cp500")
    binh = bytearray(400)

    def put(buf, offset, value, size, signed=True):
        buf[offset:offset + size] = int(value).to_bytes(size, "big", signed=signed)

    put(binh, 3217 - 3201, dt_us, 2, False)
    put(binh, 3221 - 3201, ns, 2, False)
    put(binh, 3225 - 3201, fmt, 2)
    put(binh, 3501 - 3201, 0x0100, 2, False)
    put(binh, 3503 - 3201, 1, 2)
    with open(path, "wb") as fh:
        fh.write(text)
        fh.write(bytes(binh))
        factor = 1.0 / abs(scalar) if scalar < 0 else (scalar if scalar > 0 else 1.0)
        for i in range(n):
            th = bytearray(240)
            put(th, 0, i + 1, 4)
            put(th, 70, scalar, 2)
            put(th, 108, delay_ms, 2)
            put(th, 114, ns, 2, False)
            put(th, 116, dt_us, 2, False)
            put(th, 180, round(xs[i] / factor), 4)
            put(th, 184, round(ys[i] / factor), 4)
            put(th, 188, ils[i], 4)
            put(th, 192, xls[i], 4)
            fh.write(bytes(th))
            if fmt == 5:
                fh.write(data[i].astype(">f4").tobytes())
            elif fmt == 1:
                fh.write(ieee2ibm(data[i]).astype(">u4").tobytes())
            else:
                raise ValueError("fixture writer supports formats 1 and 5")


def rotated_grid(il_values, xl_values, x0=500000.0, y0=1800000.0, spacing=25.0, angle_deg=30.0, drop=()):
    """Inline/crossline lists and XY for a rotated regular grid (optionally dropping bins)."""
    a = np.radians(angle_deg)
    ux, uy = np.cos(a), np.sin(a)      # along increasing XL
    vx, vy = -np.sin(a), np.cos(a)     # along increasing IL
    ils, xls, xs, ys = [], [], [], []
    for il in il_values:
        for xl in xl_values:
            if (il, xl) in drop:
                continue
            ils.append(il)
            xls.append(xl)
            xs.append(x0 + spacing * (xl - xl_values[0]) * ux + spacing * (il - il_values[0]) * vx)
            ys.append(y0 + spacing * (xl - xl_values[0]) * uy + spacing * (il - il_values[0]) * vy)
    return np.array(ils), np.array(xls), np.array(xs), np.array(ys)


def write_las(path, well, depth, curves: dict, null=-999.25):
    """Minimal unwrapped LAS 2.0 file. ``curves`` = {mnemonic: (unit, values)}."""
    step = depth[1] - depth[0]
    lines = ["~Version information", " VERS.   2.0 : CWLS LAS 2.0", " WRAP.   NO  : one line per depth",
             "~Well information", f" STRT.M  {depth[0]:.4f} : START DEPTH", f" STOP.M  {depth[-1]:.4f} : STOP DEPTH",
             f" STEP.M  {step:.4f} : STEP", f" NULL.   {null} : NULL VALUE", f" WELL.   {well} : WELL NAME",
             "~Curve information", " DEPT.M  : measured depth"]
    for name, (unit, _) in curves.items():
        lines.append(f" {name}.{unit}  : {name} (fixture)")
    lines.append("~A  " + " ".join(["DEPT", *curves]))
    for i, d in enumerate(depth):
        vals = [d] + [v[i] if np.isfinite(v[i]) else null for _, v in curves.values()]
        lines.append(" ".join(f"{x:.5f}" for x in vals))
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_deviation(path, well, md, azim, incl):
    rows = "\n".join(f"{m:g} {a:g} {i:g}" for m, a, i in zip(md, azim, incl))
    Path(path).write_text(f"#{well}\n#Deviation\n#MDKB (m)\n#AZIM\n#INCL\n{rows}\n", encoding="utf-8")


def write_tdr(path, well, md, twt, tvdss):
    body = "\n".join(f"{m:20.6f}{t:20.6f}{z:20.6f}" for m, t, z in zip(md, twt, tvdss))
    Path(path).write_text(f'"{well}" checkshots generated by test_fixture on Tue Nov 03 2026\n3\nMDKB\nTWT\nTVDSS\n'
                          f"{body}\n", encoding="utf-8")


def ricker(f, dt_ms, length_ms=128):
    t = np.arange(-length_ms / 2, length_ms / 2 + dt_ms / 2, dt_ms) / 1000.0
    a = (np.pi * f * t) ** 2
    return (1 - 2 * a) * np.exp(-a)


def geobody_score_cube(nI, nJ, nK, k_mid=None, seed=3):
    """Designed sand-likelihood cube with KNOWN geobody answers (software test only).

    background ~0.15; a sinuous 3-sample channel (0.85); a broad 2-sample sheet (0.72) cut by a NULL curtain
    on one inline; unseeded low-score speckles (0.5, must be rejected); a seeded 2x2x2 blob (0.9); two blobs
    touching only at a corner (separate with 6-connectivity, merged with 26)."""
    rng = np.random.default_rng(seed)
    k_mid = nK // 2 if k_mid is None else k_mid
    s = 0.15 + 0.05 * rng.random((nI, nJ, nK))
    null = np.zeros((nI, nJ, nK), bool)
    kc = max(4, k_mid - 40)
    for i in range(nI):                                   # channel: sinuous in plan view, 3 cells wide
        jc = int(round(nJ / 2 + (nJ / 5) * np.sin(i / max(2.0, nI / 6))))
        s[i, max(0, jc - 1):jc + 2, kc:kc + 3] = 0.85
    ks = min(nK - 3, k_mid + 30)
    s[2:nI - 2, 2:nJ - 2, ks:ks + 2] = 0.72               # sheet
    null[nI // 2, :, ks - 3:ks + 5] = True                # NULL curtain across the sheet
    kk = min(nK - 12, k_mid + 60)
    for _ in range(25):                                   # unseeded speckles
        s[rng.integers(0, nI), rng.integers(0, nJ), rng.integers(kk, kk + 8)] = 0.5
    kb = max(2, k_mid - 80)
    s[2:4, 2:4, kb:kb + 2] = 0.9                          # small seeded blob
    s[nI - 6:nI - 4, nJ - 6:nJ - 4, kb:kb + 2] = 0.9      # corner-touching pair
    s[nI - 4:nI - 2, nJ - 4:nJ - 2, kb + 2:kb + 4] = 0.9
    s[null] = -999.25
    return s.astype(np.float32), {"channel_k": kc, "sheet_k": ks, "blob_k": kb, "speckle_k": kk}


def overwrite_segy_samples(path, rows_ijk_values):
    """Replace the samples of an IEEE float32 big-endian SEG-Y in place (headers untouched)."""
    from geogg_fresh.segy import SegyFile

    with SegyFile(path) as s:
        ns, off, endian = s.ns, s.data_offset, s.endian
    data = np.asarray(rows_ijk_values, np.float32)
    tb = 240 + 4 * ns
    with open(path, "r+b") as fh:
        for r in range(data.shape[0]):
            fh.seek(off + r * tb + 240)
            fh.write(data[r].astype(f"{endian}f4").tobytes())


class StandInCNN:
    """Picklable numpy stand-in for the patch CNN (software tests only; works in spawned workers)."""

    def predict_numpy(self, X):
        m = np.nanmean(X.reshape(len(X), -1), axis=1)
        return {"lithology": 1 / (1 + np.exp(-3 * m)), "vsh": np.clip(0.5 + m, 0, 1), "phit": np.full(len(X), 0.2)}
